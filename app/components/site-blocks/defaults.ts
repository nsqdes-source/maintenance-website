export function editorDefaults(existing: Section[], existingItems: Item[]) {
  const sections = [...ordered(existing)],
    items = [...existingItems];
  for (const [slug, eyebrow, title, description] of headings) {
    const saved = sections.find((s) => s.slug === slug);
    const id = saved?.id ?? `new:${slug}`;
    if (!saved)
      sections.push({
        id,
        slug,
        eyebrow,
        title,
        description,
        eyebrow_en: null,
        title_en: null,
        description_en: null,
        image_url: null,
        sort_order:
          sections.reduce((n, s) => Math.max(n, s.sort_order), -1) + 1,
        is_visible: true,
        style_config: {},
      });
    // Do not resurrect deleted items of saved sections. Hero had no managed items before this phase.
    if (!saved)
      for (const [index, [title, description]] of (
        itemDefaults[slug] ?? []
      ).entries())
        items.push({
          id: `new:${slug}:${index}`,
          section_id: id,
          title,
          description,
          title_en: null,
          description_en: null,
          image_url: null,
          sort_order: index,
          is_visible: true,
        });
  }
  return { sections: ordered(sections), items };
}
